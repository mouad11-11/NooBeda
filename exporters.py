import re
import os

def expand_bus_mappings(pin_mappings: dict) -> dict:
    """
    Expands bus mappings so led[7:0] becomes led[0] through led[7] in exports.
    Supports:
      - 'led[7:0]': ['PIN_0', ..., 'PIN_7']
      - 'led[7:0]': 'PIN_0, PIN_1, ...'
      - 'led[7:0]': 'PIN_0' (single pin replicated or base)
      - 'led[0]': 'PIN_0' (already individual bits)
    """
    expanded = {}
    for port, pin in pin_mappings.items():
        bus_m = re.match(r"^([a-zA-Z0-9_]+)\[([0-9]+):([0-9]+)\]$", port.strip())
        if bus_m:
            base_name = bus_m.group(1)
            msb = int(bus_m.group(2))
            lsb = int(bus_m.group(3))
            
            # led[7:0] -> [0, 1, 2, ..., 7]
            if msb >= lsb:
                indices = list(range(lsb, msb + 1))
            else:
                indices = list(range(msb, lsb + 1))
            
            if isinstance(pin, (list, tuple)):
                pin_list = list(pin)
            elif isinstance(pin, str) and ("," in pin or " " in pin):
                pin_list = [p.strip() for p in re.split(r"[, ]+", pin) if p.strip()]
            else:
                pin_list = [pin] * len(indices)
                
            for idx, bit in enumerate(indices):
                assigned_pin = pin_list[idx] if idx < len(pin_list) else pin_list[-1]
                expanded[f"{base_name}[{bit}]"] = assigned_pin
        else:
            expanded[port] = pin
    return expanded

def build_qsf(top: str, board_family: str, board_device: str, pin_mappings: dict) -> str:
    """Builds Quartus Settings File (.qsf) content as a string."""
    pin_mappings = expand_bus_mappings(pin_mappings)
    clean_top = re.sub(r'[^a-zA-Z0-9_]', '_', top) or "top_entity"
    lines = [
        "# Quartus II Settings File - Generated by NoobEDA",
        f'set_global_assignment -name FAMILY "{board_family}"',
        f"set_global_assignment -name DEVICE {board_device}",
        f"set_global_assignment -name TOP_LEVEL_ENTITY {clean_top}\n",
    ]
    for port, pin in pin_mappings.items():
        if pin == "(Unassigned)" or not pin:
            continue
        port_clean = re.sub(r'[^a-zA-Z0-9_\[\]]', '', port)
        lines.append(f"set_location_assignment {pin} -to {port_clean}")
    return "\n".join(lines) + "\n"

def build_pcf(top: str, pin_mappings: dict) -> str:
    """Builds nextpnr Physical Constraints File (.pcf) content as a string."""
    pin_mappings = expand_bus_mappings(pin_mappings)
    lines = ["# Physical Constraints File (nextpnr) - Generated by NoobEDA"]
    for port, pin in pin_mappings.items():
        if pin == "(Unassigned)" or not pin:
            continue
        port_clean = re.sub(r'[^a-zA-Z0-9_\[\]]', '', port)
        pin_clean = pin.replace("PIN_", "")
        lines.append(f"set_io {port_clean} {pin_clean}")
    return "\n".join(lines) + "\n"

def build_xdc(top: str, pin_mappings: dict) -> str:
    """Builds Vivado Xilinx Design Constraints (.xdc) content as a string."""
    pin_mappings = expand_bus_mappings(pin_mappings)
    lines = ["# Xilinx Design Constraints (Vivado) - Generated by NoobEDA"]
    for port, pin in pin_mappings.items():
        if pin == "(Unassigned)" or not pin:
            continue
        port_clean = re.sub(r'[^a-zA-Z0-9_\[\]]', '', port)
        pin_clean = pin.replace("PIN_", "")
        lines.append(f"set_property PACKAGE_PIN {pin_clean} [get_ports {{{port_clean}}}]")
        lines.append(f"set_property IOSTANDARD LVCMOS33 [get_ports {{{port_clean}}}]")
    return "\n".join(lines) + "\n"

def parse_board_file(filepath: str):
    """
    Parses a board constraints file (.qsf, .pcf, .xdc, or .json)
    Returns: (device: str, family: str, pins: dict)
    """
    with open(filepath, "r", encoding="utf-8", errors="ignore") as fp:
        content = fp.read()
    
    device = ""
    family = ""
    pins = {}
    lower_ext = os.path.splitext(filepath)[1].lower()

    if lower_ext == ".qsf":
        dev = re.search(r"set_global_assignment\s+-name\s+DEVICE\s+(\S+)", content)
        if dev:
            device = dev.group(1)
        fam = re.search(r'set_global_assignment\s+-name\s+FAMILY\s+"?(.*?)"?$', content, re.MULTILINE)
        if fam:
            family = fam.group(1)
        for pin_code, sig in re.findall(r"set_location_assignment\s+(\S+)\s+-to\s+(\S+)", content):
            pins[sig] = pin_code
    elif lower_ext == ".pcf":
        family = "iCE40"
        for sig, pin_code in re.findall(r"set_io\s+(\S+)\s+(\S+)", content):
            pins[sig] = pin_code
    elif lower_ext == ".xdc":
        family = "Artix-7 / Xilinx"
        for pin_code, sig in re.findall(r"set_property\s+PACKAGE_PIN\s+(\S+)\s+\[get_ports\s+\{?([^\}\s]+)\}?\]", content):
            pins[sig] = pin_code
    elif lower_ext == ".json":
        import json
        data = json.loads(content)
        device = data.get("device", "")
        family = data.get("family", "")
        pins = data.get("pins", data)

    return device, family, pins
